
from pathlib import Path
import os

import pandas as pd
from sqlalchemy import create_engine, text
from sqlalchemy.engine import URL

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"

DB_USER = "postgres"
DB_PASSWORD = os.getenv("PGPASSWORD")
DB_HOST = "localhost"
DB_PORT = 5432
DB_NAME = "retail_analytics"

if not DB_PASSWORD:
    raise RuntimeError(
        "Set the PGPASSWORD environment variable to your PostgreSQL password."
    )

DATABASE_URL = URL.create(
    "postgresql+psycopg2",
    username=DB_USER,
    password=DB_PASSWORD,
    host=DB_HOST,
    port=DB_PORT,
    database=DB_NAME,
)
engine = create_engine(DATABASE_URL)


def load_data_to_db():
    customers = pd.read_csv(DATA / "customers.csv")
    stores = pd.read_csv(DATA / "stores.csv")
    products = pd.read_csv(DATA / "products.csv")
    sales = pd.read_csv(DATA / "sales_transactions.csv")

    # Load dimension tables first, preserving their database constraints.
    with engine.begin() as conn:
        for table, frame in [
            ("dim_customer", customers),
            ("dim_store", stores),
            ("dim_product", products),
        ]:
            frame.to_sql(
                table, con=conn, if_exists="append",
                index=False, method="multi"
            )

        # Calculate profit from the product cost.
        sales = sales.merge(
            products[["product_id", "unit_cost"]],
            on="product_id",
            how="left",
            validate="many_to_one",
        )
        sales["profit"] = (
            sales["total_amount"]
            - sales["quantity"] * sales["unit_cost"]
        ).round(2)

        # total_amount is generated by PostgreSQL, so don't insert it.
        sales = sales.rename(columns={"date": "sale_date"})
        sales = sales[
            [
                "transaction_id", "customer_id", "product_id",
                "store_id", "sale_date", "quantity", "unit_price",
                "profit",
            ]
        ]

        sales.to_sql(
            "sales_fact", con=conn, if_exists="append",
            index=False, method="multi"
        )

    print("ETL completed successfully.")
    print(f"Customers: {len(customers)}")
    print(f"Stores: {len(stores)}")
    print(f"Products: {len(products)}")
    print(f"Sales: {len(sales)}")


if __name__ == "__main__":
    load_data_to_db()

